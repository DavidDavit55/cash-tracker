import assert from 'node:assert/strict';
import {recordSmsKit,signedKit,actionOptions,completeTask} from './workflow-process.js';
import {readyToClose} from './workflow-model.js';
import {recordAppointmentCheck} from './agent-change-rules.js';
import {productionFields,recordProductionVerification} from './production-verification.js';
const d={id:'test',action:actionOptions[1],decisionRecorded:true};
assert.ok(!signedKit(d));assert.ok(!readyToClose(d));
const patch=recordSmsKit(d,'2026-09-28T10:00:00Z');
assert.equal(patch.kit,undefined);assert.equal(patch.clientApproved,undefined);
const sent={...d,...patch};assert.ok(signedKit(sent));assert.ok(!readyToClose(sent));
const approved={...sent,approved:true,evidence:'demo mail',effective:'2026-09-28'};
assert.ok(!readyToClose(approved),'mail approval alone does not verify an agent appointment');
Object.assign(approved,recordAppointmentCheck(approved,{date:'2026-09-28',acceptedAt:'2026-09-28',siteChecked:true,reference:'product visible under agent on company website'}));
assert.ok(readyToClose(approved));
for(const p of [{signed:false},{sent:false},{signatureSent:false},{approved:false},{missing:true},{underwritingPending:true},{sms2010:null}])assert.ok(!readyToClose({...approved,...p}));
assert.throws(()=>recordSmsKit({action:actionOptions[7]}));
const replacement={...approved,action:actionOptions[7],cancelAnnex:'ג',produced:true,tasks:{verify:{done:true}},...recordSmsKit({action:actionOptions[7],cancelAnnex:'ג'})};
Object.assign(replacement,{productCategory:'בריאות',target:'הראל',targetPremium:100,agreedCoverage:'כיסוי בדיקה',agreedExclusions:'ללא',agreedEffective:'2026-09-28',policyDocument:{data:'data:text/plain,SYNTHETIC'}});
Object.assign(replacement,recordProductionVerification(replacement,{values:Object.fromEntries(productionFields(replacement).map(f=>[f.key,f.actualOnly?'TEST-POLICY':String(f.expected)])),source:'company_document',reference:'policy checked'}));
assert.ok(signedKit(replacement));assert.ok(!signedKit({...replacement,cancelAnnex:'א'}));
const c={decisions:[replacement],products:[],appointments:[]};
assert.throws(()=>completeTask(c,'test','cancelSend',{reference:'demo separate cancellation send'}));
const updated=completeTask(c,'test','cancelCheck',{reference:'verified cancellation',when:'2026-09-28',confirmed:true,file:{data:'SYNTHETIC'}});
assert.equal(updated.decisions[0].kit,undefined);
assert.equal(updated.decisions[0].tasks.cancel,undefined);
assert.equal(updated.decisions[0].kit?.info,undefined);
assert.equal(updated.decisions[0].completed,undefined);
console.log('PASS SMS consolidated demo update, no fabricated files, no automatic completion, cancellation remains separate');
