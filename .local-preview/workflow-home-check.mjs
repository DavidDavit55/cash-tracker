import assert from 'node:assert/strict';
import {homeTasks,homePartition} from './workflow-home-model.js';
const base={id:'a',name:'דוגמה',call:'called',products:[{id:'p',category:'פנסיה'}],messages:[],decisions:[]};
const today='2026-09-28';
assert.equal(homeTasks([{...base,call:'',products:[]}],today)[0].tab,'סקירה');
const pending={id:'d',productId:'p',action:'מינוי סוכן ללא שינוי בתנאים',signatureSent:true,signatureSentAt:'2026-09-28T10:00:00+03:00'};
const tasks=homeTasks([{...base,decisions:[pending]}],today);
assert.equal(tasks[0].due,'2026-09-30');
assert.equal(homePartition(tasks,today).due.length,0);
assert.equal(homePartition(tasks,today).future.length,1);
assert.equal(homeTasks([{...base,decisions:[{...pending,completed:true}]}],today).length,0);
assert.equal(homeTasks([{...base,decisions:[{...pending,signatureSentAt:null}]}],today)[0].due,'');
const agent=homeTasks([{...base,decisions:[{...pending,sent:true,sentAt:'2026-09-28'}]}],today);
assert.equal(agent[0].due,'2026-10-12');
const many=Array.from({length:9},(_,i)=>({id:String(i),due:today,urgent:i===8}));
const part=homePartition(many,today);
assert.ok(part.visible.some(t=>t.id==='8'));
assert.equal(part.hidden,3);
assert.equal(homeTasks([{...base,decisions:[{...pending,cancellationUrgent:true}]}],today)[0].urgent,true);
console.log('PASS home: shared records, future separation, urgent visibility, completed removal, unknown date and agent timing');
