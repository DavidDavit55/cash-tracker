import assert from 'node:assert/strict';
import {depositDifference,policyClassification,changeRequests} from './workflow-detail-rules.js';
import {homeTasks} from './workflow-home-model.js';
import {buildSummary,buildKitMessage,readyToClose} from './workflow-model.js';
import {closeTreatment,businessDate} from './workflow-process.js';
const d={id:'d',productId:'p',action:'ניוד קרן פנסיה בהתאם לסיכום',sent:true,transfer:{salary:10000,employee:6,employer:6.5,severance:6,depositActual:1700,depositDate:'2026-09-29',payrollSent:true}};
const c={id:'c',name:'בדיקה',products:[{id:'p',category:'פנסיה'}],decisions:[d]};
assert.deepEqual(depositDifference(d),{expected:1850,actual:1700,gap:-150,open:true});
assert(homeTasks([c]).some(t=>t.id.endsWith('deposit-gap')&&t.title.includes('150')));
assert.equal(readyToClose(d),false);
assert.throws(()=>closeTreatment(c,d));
assert.equal(depositDifference({...d,transfer:{...d.transfer,depositResolution:'תועדה השלמה'}}).open,false);
assert.equal(depositDifference({...d,transfer:{...d.transfer,depositActual:1850}}).open,false);
assert.equal(policyClassification({isCollective:true}),'קבוצתי');
assert.equal(policyClassification({classification:'פרט'}),'אישי');
assert.equal(policyClassification({}),'לא דווח');
const change={id:'b',productId:'b',action:'מינוי סוכן וביצוע השינויים שבסיכום',sent:true,sentAt:'2026-09-01T12:00:00Z',approved:true,effective:'2026-09-29',agentAppointment:{acceptedAt:'2026-09-29'},balanceFee:.3,allocations:[{percent:100,name:'מניות',fundId:123}]};
assert.deepEqual(changeRequests(change).map(t=>[t.key,t.due]),[['track',businessDate('2026-09-01',10)],['fees','2026-12-29']]);
assert.equal(changeRequests({...change,agentAppointment:undefined}).find(t=>t.key==='fees').due,'','do not invent acceptance date from mail effective date');
c.products.push({id:'b',category:'השתלמות'},{id:'keep',category:'בריאות'});
c.decisions.push(change,{id:'keep',productId:'keep',action:'להשאיר ללא שינוי'});
assert(buildSummary(c).includes('מסלולי השקעה: 100% מניות (123)'));
const msg=buildKitMessage(c,d);
assert(msg.includes('פנסיה')&&msg.includes('השתלמות')&&msg.includes('0.3%'));
assert(!msg.includes('בריאות'));
assert(homeTasks([c]).some(t=>t.id.endsWith('change:track')));
console.log('PASS deposit 1850/1700 -> persistent 150 inquiry; closure gate; classification; change deadlines; explicit summary; combined kit');
