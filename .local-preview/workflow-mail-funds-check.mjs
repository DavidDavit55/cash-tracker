import assert from 'node:assert/strict';
import {applyCompanyMail} from './workflow-mail.js';
import {transferStage} from './workflow-transfer-stages.js';
import {readFileSync} from 'node:fs';
const d={id:'d',action:'ניוד קרן פנסיה בהתאם לסיכום',sent:true,policy:'ACTUAL-TARGET',fundsConfirmed:true,receivedAmount:100000,transfer:{inactive:true,verified:true,received:100000,document:{data:'saved-evidence'}}};
